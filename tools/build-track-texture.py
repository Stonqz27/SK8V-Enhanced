"""Build the board's wheel-track decal texture (owned, procedural) into
host/src/track_texture.inc, the .ytd bytes the ASI writes out and registers.

A skate wheel leaves a smooth groove: darker compacted floor, lighter pushed-up
rims, no tread. The texture is uniform along U (the travel direction: the
decal's side vector) so segments join without seams; V runs across the track.
The host tints it per surface with ADD_DECAL's colour. Needs numpy, Pillow and
the locked rage CLI.
"""
import argparse
import tempfile
from pathlib import Path

import numpy as np
from PIL import Image

from _common import REPO, run_rage

W, H = 16, 64  # U along travel, V across


def image():
    v = (np.arange(H) + 0.5) / H * 2 - 1          # -1..1 across the track
    floor = np.exp(-(v / 0.45) ** 2)              # the groove
    rims = np.exp(-((np.abs(v) - 0.72) / 0.14) ** 2)  # material pushed aside
    grey = np.clip(1.0 - 0.45 * floor + 0.15 * rims, 0, 1)
    alpha = np.clip(0.85 * floor + 0.45 * rims, 0, 1) * (np.abs(v) < 0.98)
    px = np.zeros((H, W, 4), np.uint8)
    px[..., :3] = np.rint(grey * 255)[:, None, None]
    px[..., 3] = np.rint(alpha * 255)[:, None]
    return Image.fromarray(px, 'RGBA')


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--rage', type=Path, default=REPO / 'build/tools/rage.exe')
    p.add_argument('--out', type=Path, default=REPO / 'host/src/track_texture.inc')
    a = p.parse_args()
    with tempfile.TemporaryDirectory() as tmp:
        png = Path(tmp) / 'skatev_track.png'
        image().save(png)
        ytd = Path(tmp) / 'skatev_tracks.ytd'
        run_rage(a.rage, 'textures', 'build', png, '-o', ytd, '-f', 'rgba8')
        data = ytd.read_bytes()
    rows = [', '.join(f'0x{b:02x}' for b in data[i:i + 24]) for i in range(0, len(data), 24)]
    a.out.write_text('// Generated by tools/build-track-texture.py: skatev_tracks.ytd (texture skatev_track).\n'
                     + ',\n'.join(rows) + '\n', encoding='ascii', newline='\n')
    print(f'{a.out}: {len(data)} bytes')


if __name__ == '__main__':
    main()
